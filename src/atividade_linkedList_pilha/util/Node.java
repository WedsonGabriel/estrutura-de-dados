package atividade_linkedList_pilha.util;

public class Node {
    // ATRIBUTOS
    private String value;
    private Node next;

    // GETTERS AND SETTERS
    public String getValue() {
        return value;
    }
    public void setValue(String value) {
        this.value = value;
    }
    public Node getNext() {
        return next;
    }
    public void setNext(Node next) {
        this.next = next;
    }
}
